/// 由 Unihan 生成汉字拼音表 `lib/utils/pinyin/pinyin_table.dart`。
///
/// 用法（仓库根目录）：
/// ```text
/// # 下载并解压 https://www.unicode.org/Public/UCD/latest/ucd/Unihan.zip
/// dart run tool/generate_pinyin_table.dart <Unihan_Readings.txt>
/// ```
///
/// 只收 CJK 统一汉字基本区（U+4E00–U+9FFF），每字取 `kMandarin` 的第一个
/// 读音（Unihan 定义为“最通行的读音”，简体优先），去掉声调，ü 记作 v。
/// 多音字只有这一个读音：按字母排序与拼音检索够用，不做词组消歧。
///
/// 为什么自带表而不引入拼音库：现成的库把整本字典与词组表以 JSON 字符串
/// 编进安装包（约 4MB）并在首次使用时整份解析；这里每字只占两个字符，
/// 整张表约 42KB，按码位直接取值。
///
/// 编码：每个码位两个字符（[_alphabet] 里的 64 进制），值为音节序号 + 1，
/// 0 表示该码位没有读音；音节按字母序排列、以空格分隔。
library;

import 'dart:io';

const int _first = 0x4E00;
const int _last = 0x9FFF;
const String _alphabet =
    '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz-_';
const String _output = 'lib/utils/pinyin/pinyin_table.dart';

/// 带声调的字母 → 去声调后的字母（ü 系列记作 v）。组合附加符号另行剔除。
const Map<String, String> _toneless = <String, String>{
  'ā': 'a', 'á': 'a', 'ǎ': 'a', 'à': 'a', //
  'ē': 'e', 'é': 'e', 'ě': 'e', 'è': 'e', //
  'ê': 'e', 'ế': 'e', 'ề': 'e', //
  'ī': 'i', 'í': 'i', 'ǐ': 'i', 'ì': 'i', //
  'ō': 'o', 'ó': 'o', 'ǒ': 'o', 'ò': 'o', //
  'ū': 'u', 'ú': 'u', 'ǔ': 'u', 'ù': 'u', //
  'ü': 'v', 'ǖ': 'v', 'ǘ': 'v', 'ǚ': 'v', 'ǜ': 'v', //
  'ń': 'n', 'ň': 'n', 'ǹ': 'n', 'ḿ': 'm', //
};

void main(List<String> args) {
  if (args.length != 1) {
    _fail(
      'Usage: dart run tool/generate_pinyin_table.dart <Unihan_Readings.txt>',
    );
  }
  final source = File(args.single);
  if (!source.existsSync()) _fail('${source.path} does not exist');

  String? version;
  final readings = <int, String>{};
  for (final line in source.readAsLinesSync()) {
    if (line.startsWith('# Unicode Version')) {
      version = line.substring(2).trim();
      continue;
    }
    if (!line.startsWith('U+')) continue;
    final fields = line.split('\t');
    if (fields.length < 3 || fields[1] != 'kMandarin') continue;
    final codePoint = int.parse(fields[0].substring(2), radix: 16);
    if (codePoint < _first || codePoint > _last) continue;
    readings[codePoint] = _stripTone(fields[2].split(' ').first);
  }
  if (readings.isEmpty) _fail('no kMandarin readings in ${source.path}');

  final syllables = readings.values.toSet().toList()..sort();
  if (syllables.length >= _alphabet.length * _alphabet.length) {
    _fail('too many syllables: ${syllables.length}');
  }
  final indexOf = <String, int>{
    for (var i = 0; i < syllables.length; i++) syllables[i]: i + 1,
  };
  final data = StringBuffer();
  for (var codePoint = _first; codePoint <= _last; codePoint++) {
    final value = indexOf[readings[codePoint]] ?? 0;
    data
      ..write(_alphabet[value ~/ _alphabet.length])
      ..write(_alphabet[value % _alphabet.length]);
  }

  File(_output).writeAsStringSync(
    _render(
      version: version ?? 'unknown version',
      syllables: syllables.join(' '),
      data: data.toString(),
    ),
  );
  stdout.writeln(
    'Wrote $_output: ${readings.length} characters, '
    '${syllables.length} syllables. Run `dart format $_output` next.',
  );
}

String _stripTone(String reading) {
  final buffer = StringBuffer();
  for (final rune in reading.toLowerCase().runes) {
    // 组合附加符号（如 ê̄ 里的 U+0304）。
    if (rune >= 0x0300 && rune <= 0x036F) continue;
    final char = String.fromCharCode(rune);
    buffer.write(_toneless[char] ?? char);
  }
  final result = buffer.toString();
  if (!RegExp(r'^[a-z]+$').hasMatch(result)) {
    _fail('unexpected reading "$reading" -> "$result"');
  }
  return result;
}

String _render({
  required String version,
  required String syllables,
  required String data,
}) {
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_pinyin_table.dart. Do not edit.')
    ..writeln('//')
    ..writeln('// Source: Unicode Han Database (Unihan), kMandarin field,')
    ..writeln('// $version. Copyright © Unicode, Inc.; used under the')
    ..writeln('// Unicode License v3 (https://www.unicode.org/license.txt).')
    ..writeln()
    ..writeln('/// 拼音表收录的第一个码位（CJK 统一汉字基本区）。')
    ..writeln(
      'const int pinyinTableFirstCodePoint = '
      '0x${_first.toRadixString(16).toUpperCase()};',
    )
    ..writeln()
    ..writeln('/// 拼音表收录的最后一个码位。')
    ..writeln(
      'const int pinyinTableLastCodePoint = '
      '0x${_last.toRadixString(16).toUpperCase()};',
    )
    ..writeln()
    ..writeln('/// 两位编码所用的 64 个字符，序号即数值。')
    ..writeln("const String pinyinTableAlphabet = '$_alphabet';")
    ..writeln()
    ..writeln('/// 去声调的音节（ü 记作 v），按字母序、以空格分隔。')
    ..writeln('const String pinyinTableSyllables =');
  _writeChunks(out, syllables, splitOnSpace: true);
  out
    ..writeln()
    ..writeln('/// 每个码位两个字符：音节序号 + 1，0 表示没有读音。')
    ..writeln('const String pinyinTableData =');
  _writeChunks(out, data, splitOnSpace: false);
  return out.toString();
}

/// 把长字符串写成相邻的字符串字面量（编译期拼接），每行不超过 80 列。
void _writeChunks(
  StringBuffer out,
  String value, {
  required bool splitOnSpace,
}) {
  const width = 80 - 4 - 2; // 缩进 4 + 一对引号。
  final chunks = <String>[];
  var start = 0;
  while (start < value.length) {
    var end = start + width;
    if (end >= value.length) {
      end = value.length;
    } else if (splitOnSpace) {
      // 在空格之后断行，保证每段都以完整音节结尾。
      end = value.lastIndexOf(' ', end - 1) + 1;
    }
    chunks.add(value.substring(start, end));
    start = end;
  }
  for (var i = 0; i < chunks.length; i++) {
    final terminator = i == chunks.length - 1 ? ';' : '';
    out.writeln("    '${chunks[i]}'$terminator");
  }
}

Never _fail(String message) {
  stderr.writeln(message);
  exit(1);
}
